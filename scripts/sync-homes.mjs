// Copies src/data/products.mjs and src/components/ProductHome.astro into each
// product's docs site, at the fixed paths in SITES below, each with a header
// saying the file is generated and must be edited here.
//
//   npm run sync-homes                 write the copies
//   npm run sync-homes -- --check      report drift and exit 1 on any; writes nothing
//
// The product checkouts are siblings of this one. `--root <dir>` names the
// directory that holds them (default: the parent of this checkout) and
// `--suffix <text>` is appended to each checkout's directory name, for a
// worktree such as chant-homes.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Each product's checkout, and the docs site inside it.
const SITES = [
	{ repo: 'chant', site: 'docs' },
	{ repo: 'terragucci', site: 'docs-site' },
	{ repo: 'plywood', site: 'site' },
	{ repo: 'choudoufu', site: 'site' },
	{ repo: 'plunge', site: 'site' },
	{ repo: 'behold', site: 'docs' },
];

// What is copied, from here to a path inside each site.
const FILES = [
	{ from: 'src/data/products.mjs', to: 'src/data/products.mjs', kind: 'mjs' },
	{ from: 'src/components/ProductHome.astro', to: 'src/components/ProductHome.astro', kind: 'astro' },
];

const args = process.argv.slice(2);
const check = args.includes('--check');
const opt = (name, fallback) => {
	const i = args.indexOf(name);
	return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};
const root = resolve(opt('--root', join(here, '..')));
const suffix = opt('--suffix', '');

const header = (from) => `GENERATED by \`npm run sync-homes\` in intentius.github.io. Do not edit this copy: edit ${from} there and sync again.`;

/** The source with the generated header added: before the code in an .mjs file, inside the frontmatter of an .astro one. */
const generated = (file, text) => {
	if (file.kind === 'mjs') return `// ${header(file.from)}\n${text}`;
	if (!text.startsWith('---\n')) throw new Error(`${file.from} must open with Astro frontmatter`);
	return `---\n// ${header(file.from)}\n${text.slice(4)}`;
};

let drift = 0;
let missing = 0;
for (const { repo, site } of SITES) {
	const dir = join(root, repo + suffix, site);
	if (!existsSync(dir)) {
		console.error(`missing: ${dir}`);
		missing++;
		continue;
	}
	for (const file of FILES) {
		const want = generated(file, readFileSync(join(here, file.from), 'utf8'));
		const dest = join(dir, file.to);
		const have = existsSync(dest) ? readFileSync(dest, 'utf8') : null;
		if (have === want) {
			console.log(`ok: ${repo}/${site}/${file.to}`);
		} else if (check) {
			console.log(`${have === null ? 'absent' : 'drift'}: ${repo}/${site}/${file.to}`);
			drift++;
		} else {
			mkdirSync(dirname(dest), { recursive: true });
			writeFileSync(dest, want);
			console.log(`wrote: ${repo}/${site}/${file.to}`);
		}
	}
}

if (missing) process.exit(2);
if (check && drift) {
	console.error(`${drift} file(s) differ from intentius.github.io. Run \`npm run sync-homes\` and commit the result in each product.`);
	process.exit(1);
}
